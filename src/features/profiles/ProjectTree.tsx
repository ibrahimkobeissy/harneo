import { FileText, Folder } from "lucide-react";
import { useEffect, useMemo, useState } from "react";
import type { Layout } from "../../bindings/Layout";
import type { PlannedPath } from "../../bindings/PlannedPath";
import type { Resolved } from "../../bindings/Resolved";
import { libraryDetail } from "../../lib/ipc";
import { Panel } from "../../ui";
import styles from "./Builder.module.css";
import { sourceLabel, treeRows } from "./spec";

const generatedLabel = {
  harnessMd: "Generated by Harneo",
  mcpJson: "Generated by Harneo from the MCP servers",
  settings: "Generated by Harneo from the Settings template",
} as const;

/** The project the profile produces, live from `profile_layout`. */
export function ProjectTree({
  layout,
  resolved,
  onManualOnly,
}: {
  layout: Layout | null;
  resolved: Resolved | null;
  onManualOnly: (id: string, value: boolean) => void;
}) {
  const [selected, setSelected] = useState<string | null>(null);
  const rows = useMemo(() => (layout ? treeRows(layout) : []), [layout]);
  const planned = layout?.paths.find((p) => p.path === selected);
  const conflicts = layout?.conflicts ?? [];

  return (
    <Panel
      title="The project it produces"
      titleId="cart-tree"
      aside={
        <span className={styles.panelNote}>
          {layout?.paths.length ?? 0}{" "}
          {layout?.paths.length === 1 ? "file" : "files"}
        </span>
      }
    >
      {rows.length === 0 && (
        <p className={styles.quiet}>
          The files appear here as you add artifacts.
        </p>
      )}
      {conflicts.length > 0 && (
        <p role="alert" className={styles.errorText}>
          {conflicts.length === 1
            ? "1 path is claimed twice:"
            : `${conflicts.length} paths are claimed twice:`}{" "}
          {conflicts.map((c) => c.path).join(", ")}
        </p>
      )}
      {rows.length > 0 && (
        <ul className={styles.tree} aria-label="Project files">
          {rows.map((row) => (
            <li
              key={row.path}
              style={{ paddingInlineStart: `${row.depth * 14}px` }}
            >
              {row.file ? (
                <button
                  type="button"
                  className={`${styles.treeFile} ${row.conflict ? styles.conflict : ""} ${selected === row.path ? styles.treeOn : ""}`}
                  aria-pressed={selected === row.path}
                  title={
                    row.conflict
                      ? `${row.path}: two artifacts claim this path`
                      : row.path
                  }
                  onClick={() =>
                    setSelected(selected === row.path ? null : row.path)
                  }
                >
                  <FileText size={13} aria-hidden="true" />
                  {row.name}
                  {row.conflict && (
                    <span className={styles.conflictTag}>conflict</span>
                  )}
                </button>
              ) : (
                <span className={styles.treeDir}>
                  <Folder size={13} aria-hidden="true" />
                  {row.name}
                </span>
              )}
            </li>
          ))}
        </ul>
      )}
      {planned && (
        <FileInfo
          planned={planned}
          resolved={resolved}
          conflict={conflicts.find((c) => c.path === planned.path)?.artifacts}
          onManualOnly={onManualOnly}
        />
      )}
    </Panel>
  );
}

function FileInfo({
  planned,
  resolved,
  conflict,
  onManualOnly,
}: {
  planned: PlannedPath;
  resolved: Resolved | null;
  conflict: string[] | undefined;
  onManualOnly: (id: string, value: boolean) => void;
}) {
  const artifactId =
    planned.from.type === "artifact" ? planned.from.artifact : null;
  const item = resolved?.artifacts.find((a) => a.id === artifactId);
  const [loaded, setLoaded] = useState<{ id: string; label: string } | null>(
    null,
  );
  const source = loaded?.id === artifactId ? loaded.label : null;

  useEffect(() => {
    if (artifactId === null) return;
    let stale = false;
    libraryDetail(artifactId).then(
      (d) => {
        if (!stale && artifactId) {
          setLoaded({
            id: artifactId,
            label: sourceLabel(d.provenance.source),
          });
        }
      },
      () => undefined,
    );
    return () => {
      stale = true;
    };
  }, [artifactId]);

  const names = (conflict ?? []).map(
    (id) => resolved?.artifacts.find((a) => a.id === id)?.name ?? id,
  );
  return (
    <div className={styles.callout}>
      <FileText size={14} aria-hidden="true" />
      <div className={styles.fileInfo}>
        <b className={styles.mono}>{planned.path}</b>
        <p>
          {planned.from.type === "generated"
            ? generatedLabel[planned.from.generated]
            : `From ${item?.name ?? planned.from.artifact}${source ? ` · ${source}` : ""}`}
        </p>
        {names.length > 1 && (
          <p className={styles.errorText}>Claimed by {names.join(" and ")}.</p>
        )}
        {item && item.kind === "skill" && (
          <div className={styles.switchRow}>
            <span>Manual only</span>
            <button
              type="button"
              role="switch"
              aria-checked={item.manualOnly}
              aria-label={`Manual only for ${item.name}`}
              className={`${styles.toggle} ${item.manualOnly ? styles.toggleOn : ""}`}
              onClick={() => onManualOnly(item.id, !item.manualOnly)}
            >
              <i />
            </button>
          </div>
        )}
      </div>
    </div>
  );
}

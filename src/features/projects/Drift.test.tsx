const NOW = Math.floor(Date.now() / 1000);

function project(id: number, name: string): Project {
  return {
    id: BigInt(id),
    path: `/work/${name}`,
    name,
    profileId: 10n,
    profileName: "Heavy",
    profileVersion: 4,
    appliedAt: BigInt(NOW - 3600),
    fileCount: 5,
    removedAt: null,
  };
}

const edited = {
  path: ".claude/agents/code-reviewer.md",
  change: { type: "edited", plus: 6, minus: 2 },
  artifact: "agent:code-reviewer",
  promoteBlocked: null,
} as const;
const deleted = {
  path: ".claude/commands/test.md",
  change: { type: "deleted" },
  artifact: "command:test",
  promoteBlocked:
    ".claude/commands/test.md was deleted; only re-apply can bring it back",
} as const;
const generated = {
  path: ".claude/settings.json",
  change: { type: "edited", plus: 2, minus: 0 },
  artifact: null,
  promoteBlocked:
    ".claude/settings.json is generated by Harneo; re-apply it instead",
} as const;
const added = {
  path: ".claude/skills/mine/SKILL.md",
  change: { type: "added" },
  artifact: null,
  promoteBlocked: null,
} as const;

function report(over: Partial<DriftReport> = {}): DriftReport {
  return {
    status: "drift",
    files: [edited, deleted, generated, added],
    libraryNewer: [],
    profileNewer: null,
    ...over,
  };
}

function plan(): Plan {
  const write = (path: string, action: "replace" | "new") => ({
    path,
    action,
    bytes: null,
    diff: null,
    artifact: null,
  });
  return {
    target: "/work/shop",
    profileId: 10n,
    profileName: "Heavy",
    profileVersion: 4,
    reason: "Re-apply",
    writes: [
      write(edited.path, "replace"),
      write(deleted.path, "new"),
      { ...write("HARNESS.md", "replace"), action: "keep" },
    ],
    backupCount: 2,
    kind: "reapply",
    editedInProject: [],
    restored: [],
    warnings: [],
  } as unknown as Plan;
}

interface Opts {
  forgetError?: boolean;
  report?: DriftReport | null;
  checkError?: boolean;
  diffError?: boolean;
  planError?: boolean;
  applyError?: boolean;
  applyGate?: Promise<void>;
  promoteError?: boolean;
  addedError?: boolean;
  candidate?: string | null;
  summaries?: { projectId: bigint; summary: DriftSummary }[];
  projects?: Project[];
}

function Where() {
  const l = useLocation();
  return <p data-testid="where">{l.pathname + l.search}</p>;
}

function setup(path: string, opts: Opts = {}) {
  const calls: { cmd: string; args: unknown }[] = [];
  mockIPC(
    (cmd, args) => {
      calls.push({ cmd, args });
      switch (cmd) {
        case "projects_list":
          return opts.projects ?? [project(1, "shop")];
        case "project_get":
          return (opts.projects ?? [project(1, "shop")])[0];
        case "profiles_list":
          return [
            {
              id: 10,
              name: "Heavy",
              description: "",
              version: 4,
              counts: [],
              fileCount: 1,
              projectCount: 1,
              updatedAt: 1,
            },
          ];
        case "project_files":
        case "project_backups":
          return [];
        case "app_info":
          return { version: "1", dataDir: "/data" };
        case "drift_check":
          if (opts.checkError) throw new Error("boom");
          return opts.report === undefined ? report() : opts.report;
        case "drift_check_all":
          return opts.summaries ?? [];
        case "drift_diff":
          if (opts.diffError) throw new Error("no diff");
          return [
            {
              oldStart: 1,
              newStart: 1,
              lines: [
                { kind: "context", text: "---" },
                { kind: "removed", text: "tools: Read, Bash" },
                { kind: "added", text: "tools: Read" },
              ],
            },
          ];
        case "drift_reapply_plan":
          if (opts.planError) throw new Error("no plan");
          return plan();
        case "install_apply":
          if (opts.applyError) throw new Error("disk full");
          if (opts.applyGate)
            return opts.applyGate.then(() => ({ written: 2 }));
          return { written: 2 };
        case "project_forget_missing":
          if (opts.forgetError) throw new Error("still there");
          return null;
        case "drift_promote":
          if (opts.promoteError) throw new Error("audit refused it");
          return { path: edited.path, artifact: "a", backup: "b" };
        case "drift_promote_added":
          if (opts.addedError) throw new Error("nothing there");
          return {
            preview: { source: { kind: "local", path: "/work/shop" } },
            candidate:
              opts.candidate === undefined ? "id-mine" : opts.candidate,
          };
        default:
          return null;
      }
    },
    { shouldMockEvents: true },
  );
  render(
    <MemoryRouter initialEntries={[path]}>
      <CollectionsProvider>
        <Sidebar
          onShortcuts={() => undefined}
          onSearch={() => undefined}
          onCollapse={() => undefined}
        />
        <Routes>
          <Route path="/projects" element={<ProjectsScreen />} />
          <Route path="/projects/:id" element={<ProjectScreen />} />
          <Route path="*" element={<Where />} />
        </Routes>
      </CollectionsProvider>
    </MemoryRouter>,
  );
  return calls;
}

const summary = (over: Partial<DriftSummary> = {}): DriftSummary => ({
  status: "inSync",
  drifted: 0,
  libraryNewer: 0,
  profileNewer: null,
  ...over,
});

describe("statusOf with drift", () => {
  const p = project(1, "x");
  it("weighs missing, drift, profile, library, sync in that order", () => {
    const counts = (d: Partial<DriftSummary>) => ({
      status: "inSync" as const,
      drifted: 0,
      libraryNewer: 0,
      ...d,
    });
    expect(statusOf(p, 5, counts({ status: "missing", drifted: 2 }))).toEqual({
      kind: "missing",
    });
    expect(statusOf(p, 5, counts({ drifted: 2 }))).toEqual({
      kind: "drift",
      files: 2,
    });
    expect(statusOf(p, 5, counts({ libraryNewer: 1 }))).toEqual({
      kind: "available",
      version: 5,
    });
    expect(statusOf(p, 4, counts({ libraryNewer: 1 }))).toEqual({
      kind: "library",
    });
    expect(statusOf(p, 4, counts({}))).toEqual({ kind: "sync" });
  });
});


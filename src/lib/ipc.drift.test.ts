import { mockIPC } from "@tauri-apps/api/mocks";
import { describe, expect, it } from "vitest";
import {
  driftCheck,
  driftCheckAll,
  driftDiff,
  driftPromote,
  driftPromoteAdded,
  driftReapplyPlan,
} from "./ipc";

function record(result: unknown) {
  const calls: { cmd: string; args: unknown }[] = [];
  mockIPC((cmd, args) => {
    calls.push({ cmd, args });
    return result;
  });
  return calls;
}

describe("drift wrappers", () => {
  it("send ids as numbers with the command's argument names", async () => {
    const calls = record("r");
    expect(await driftCheck(4n)).toBe("r");
    expect(await driftCheckAll()).toBe("r");
    expect(await driftDiff(4n, "a.md")).toBe("r");
    expect(await driftReapplyPlan(4n)).toBe("r");
    await driftReapplyPlan(4n, ["a.md"]);
    expect(await driftPromote(4n, "a.md")).toBe("r");
    expect(await driftPromoteAdded(4n, "b.md")).toBe("r");
    expect(calls).toEqual([
      { cmd: "drift_check", args: { id: 4 } },
      { cmd: "drift_check_all", args: {} },
      { cmd: "drift_diff", args: { projectId: 4, path: "a.md" } },
      { cmd: "drift_reapply_plan", args: { projectId: 4, paths: null } },
      { cmd: "drift_reapply_plan", args: { projectId: 4, paths: ["a.md"] } },
      { cmd: "drift_promote", args: { projectId: 4, path: "a.md" } },
      { cmd: "drift_promote_added", args: { projectId: 4, path: "b.md" } },
    ]);
  });

  it("reject with the backend's message", async () => {
    mockIPC(() => {
      throw "a.md is generated by Harneo";
    });
    await expect(driftPromote(4n, "a.md")).rejects.toBe(
      "a.md is generated by Harneo",
    );
    await expect(driftCheck(4n)).rejects.toBe("a.md is generated by Harneo");
  });
});
